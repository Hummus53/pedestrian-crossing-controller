/**
  * @brief  The application entry point.
  * @retval int
  */
int main(void)
{

  /* USER CODE BEGIN 1 */

  /* USER CODE END 1 */

  /* MCU Configuration--------------------------------------------------------*/

  /* Reset of all peripherals, Initializes the Flash interface and the Systick. */
  HAL_Init();

  /* USER CODE BEGIN Init */

  /* USER CODE END Init */

  /* Configure the system clock */
  SystemClock_Config();

  /* USER CODE BEGIN SysInit */

  /* USER CODE END SysInit */

  /* Initialize all configured peripherals */
  MX_GPIO_Init();
  MX_TIM2_Init();
  MX_USART2_UART_Init();
  /* USER CODE BEGIN 2 */
  HAL_TIM_Base_Start_IT(&htim2);

  void set_lights(uint8_t red, uint8_t yellow, uint8_t green, uint8_t walk) {
	  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_0, red ? GPIO_PIN_SET : GPIO_PIN_RESET);
	  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_1, yellow ? GPIO_PIN_SET : GPIO_PIN_RESET);
	  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_2, green ? GPIO_PIN_SET : GPIO_PIN_RESET);
	  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_3, walk ? GPIO_PIN_SET : GPIO_PIN_RESET);
  }
  /* USER CODE END 2 */

  /* Initialize leds */
  BSP_LED_Init(LED2);

  /* Initialize USER push-button, will be used to trigger an interrupt each time it's pressed.*/
  BSP_PB_Init(BUTTON_USER, BUTTON_MODE_EXTI);

  /* Infinite loop */
  /* USER CODE BEGIN WHILE */
  while (1)
  {
	  switch (state) {
	  case CAR_GREEN:
		  set_lights(0, 0, 1, 0);
		  if (ped_request && phase_seconds >= 2) {
			  state = CAR_YELLOW;
			  phase_seconds = 0;
			  ped_request = 0;
			  printf("t=%lu ms: -> CAR YELLOW\r\n", HAL_GetTick());
		  } else if (phase_seconds >= 12) {
			  state = CAR_YELLOW;
			  phase_seconds = 0;
			  printf("t=%lu ms: -> CAR YELLOW\r\n", HAL_GetTick());
		  }
		  break;
	  case CAR_YELLOW:
		  set_lights(0, 1, 0, 0);
		  if (phase_seconds >= 2) {
			  state = CAR_RED_WALK;
			  phase_seconds = 0;
			  printf("t=%lu ms: -> CAR_RED_WALK\r\n", HAL_GetTick());
		  }
		  break;
	  case CAR_RED_WALK:
		  set_lights(1, 0, 0, 1);
		  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_5, GPIO_PIN_SET);
		  if (phase_seconds >= 5) {
			  state = CAR_RED_WALK_FLASH;
			  phase_seconds = 0;
			  printf("t=%lu ms: -> CAR_RED_WALK_FLASH\r\n", HAL_GetTick());
		  }
		  break;
	  case CAR_RED_WALK_FLASH:
		  set_lights(1, 0, 0, (phase_seconds % 2 == 0)); // flash walk LED
		  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_5, (phase_seconds % 2 == 0) ? GPIO_PIN_SET : GPIO_PIN_RESET);
		  if (phase_seconds >= 3) {
			  state = CAR_GREEN;
			  phase_seconds = 0;
			  HAL_GPIO_WritePin(GPIOB, GPIO_PIN_5, GPIO_PIN_RESET);
			  printf("t=%lu ms: -> CAR_GREEN\r\n", HAL_GetTick());
		  }
		  break;
	  }
    /* USER CODE END WHILE */

    /* USER CODE BEGIN 3 */
  }
  /* USER CODE END 3 */
}

